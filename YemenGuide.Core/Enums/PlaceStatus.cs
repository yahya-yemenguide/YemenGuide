namespace YemenGuide.Core.Enums
{
    /// <summary>
    /// يمثل الحالات القانونية والبرمجية للمنشآت والأماكن داخل المنصة.
    /// </summary>
    public enum PlaceStatus
    {
        // قيد المراجعة: الحالة الافتراضية عند قيام المالك بإضافة منشأة جديدة، وتنتظر موافقة مدير النظام لتظهر للعامة.
        Pending,

        // مقبولة ونشطة: تعني أن مدير النظام وافق على المنشأة، وهي الآن تظهر لجميع الزوار ويمكن الحجز فيها.
        Approved,

        // مرفوضة: تعني أن المنشأة لم تستوفِ الشروط وتم رفضها من قِبل الإدارة (يمكن للمالك تعديلها وإعادة إرسالها).
        Rejected,

        // موقوفة مؤقتاً: تعني أن المنشأة مخفية عن الزوار مؤقتاً بسبب مخالفة شروط المنصة أو بطلب من المالك نفسه.
        Suspended
    }
}
