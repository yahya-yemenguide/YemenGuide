namespace YemenGuide.Core.Enums
{
    /// <summary>
    /// يمثل حالة طلب الحجز الذي يقوم به العميل في أي منشأة.
    /// </summary>
    public enum BookingStatus
    {
        // بانتظار التأكيد: العميل أرسل طلب الحجز، والنظام بانتظار موافقة المالك أو تأكيد دفع العربون.
        Pending,

        // مؤكد: تم قبول الحجز وتأكيد الدفع بنجاح، والمكان محجوز للعميل في التاريخ المحدد.
        Confirmed,

        // مكتمل: تعني أن العميل حضر بالفعل للمنشأة واستفاد من الحجز وانتهت المدة بنجاح.
        Completed,

        // ملغي: تم إلغاء الحجز إما من قِبل العميل أو المالك (مع تفعيل سياسة الاسترجاع إن وجدت).
        Cancelled
    }
}
